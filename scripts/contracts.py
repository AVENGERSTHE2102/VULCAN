"""Generate UI types from Pydantic schemas; fail checks on contract drift."""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))
from lab.contracts import ContextSegment, Proposal, Decision, ToolResult, AuditEvent


def ts(s):
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "anyOf" in s:
        return " | ".join(ts(x) for x in s["anyOf"])
    if s.get("type") == "array":
        return "(" + ts(s["items"]) + ")[]"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
        "object": "Record<string, unknown>",
    }.get(s.get("type"), "unknown")


text = "// Generated by scripts/contracts.py. Do not edit.\n"
for model in (ContextSegment, Proposal, Decision, ToolResult, AuditEvent):
    s = model.model_json_schema()
    text += "export interface " + model.__name__ + " {\n"
    for k, v in s["properties"].items():
        text += f"  {k}{'' if k in s.get('required', []) else '?'}: {ts(v)};\n"
    text += "}\n"
path = Path(__file__).resolve().parents[1] / "frontend/src/contracts.ts"
if "--check" in sys.argv:
    assert path.read_text() == text, "Run uv run python scripts/contracts.py"
else:
    path.write_text(text)
